"""Opt-in private local report history; no daemon, network, or host changes.

History order is save time encoded in filenames, not untrusted report metadata.
Only anchored LinScope filenames are considered. Corrupt or unsafe history
entries are reported rather than silently disappearing from comparisons.
"""
from __future__ import annotations

from copy import deepcopy
from datetime import datetime, timezone
import fcntl
import json
import os
from pathlib import Path
import re
import stat
import uuid

from linscope.reporting import _findings

MAX_REPORT_BYTES = 8_388_608
MAX_CANDIDATES = 500
MAX_DIRECTORY_ENTRIES = 10_000
_NAME = re.compile(r"linscope-[0-9]{8}T[0-9]{12}Z-[0-9a-f]{32}\.json", re.ASCII)


def _validate_report(report):
    findings = _findings(report)
    if not isinstance(report.get("generated_at"), str) or not report["generated_at"]:
        raise ValueError("History report requires generated_at text")
    try:
        stamp = datetime.fromisoformat(report["generated_at"].replace("Z", "+00:00"))
    except ValueError as exc:
        raise ValueError("History generated_at must be an ISO timestamp") from exc
    if stamp.tzinfo is None or stamp.utcoffset() is None:
        raise ValueError("History generated_at must include a timezone")
    if report.get("tool", {}).get("name") != "LinScope":
        raise ValueError("History accepts reports generated by LinScope only")
    if not isinstance(report.get("tool", {}).get("version"), str) or not report["tool"]["version"]:
        raise ValueError("History report requires a tool version string")
    return findings


def _open_directory(directory, create=False):
    path = Path(directory).absolute()
    if create:
        path.mkdir(mode=0o700, parents=True, exist_ok=True)
    try:
        fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
    except FileNotFoundError:
        if not create:
            return path, None
        raise
    try:
        metadata = os.fstat(fd)
        if metadata.st_uid != os.geteuid() or stat.S_IMODE(metadata.st_mode) != 0o700:
            raise ValueError("History directory must be owned by the effective user and have mode 0700")
    except BaseException:
        os.close(fd)
        raise
    return path, fd


def _candidate_names(directory_fd):
    names, count = [], 0
    with os.scandir(directory_fd) as entries:
        for entry in entries:
            count += 1
            if count > MAX_DIRECTORY_ENTRIES:
                raise ValueError("History directory exceeds the bounded entry-inspection limit")
            if _NAME.fullmatch(entry.name):
                names.append(entry.name)
                if len(names) > MAX_CANDIDATES:
                    raise ValueError(f"History exceeds the {MAX_CANDIDATES}-report inspection limit; archive older reports explicitly")
    return sorted(names, reverse=True)


def _unique_object(pairs):
    value = {}
    for key, item in pairs:
        if key in value:
            raise ValueError("Duplicate JSON object key")
        value[key] = item
    return value


def _invalid_constant(value):
    raise ValueError("Non-finite JSON constants are not accepted")


def _read_report(directory_fd, name):
    try:
        fd = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC,
                     dir_fd=directory_fd)
        with os.fdopen(fd, "rb") as stream:
            metadata = os.fstat(stream.fileno())
            if (not stat.S_ISREG(metadata.st_mode) or metadata.st_uid != os.geteuid()
                    or stat.S_IMODE(metadata.st_mode) & ~0o600 or metadata.st_nlink != 1):
                raise ValueError("Report must be a private, unlinked-to-other-paths regular file owned by the effective user")
            if metadata.st_size > MAX_REPORT_BYTES:
                raise ValueError("Report exceeds the 8 MiB history limit")
            raw = stream.read(MAX_REPORT_BYTES + 1)
        if len(raw) > MAX_REPORT_BYTES:
            raise ValueError("Report exceeds the 8 MiB history limit")
        report = json.loads(raw.decode("utf-8"), object_pairs_hook=_unique_object,
                            parse_constant=_invalid_constant)
        _validate_report(report)
        # Validate all additional JSON fields too, even if a renderer does not
        # use them. For example 1e999 parses as infinity without parse_constant.
        json.dumps(report, ensure_ascii=True, allow_nan=False)
        return report
    except (OSError, ValueError, TypeError, RecursionError) as exc:
        raise ValueError(f"History report {name} could not be safely read: {exc}") from exc


def _reports(directory_fd):
    # Stream bounded reports instead of retaining up to 500 large documents.
    for name in _candidate_names(directory_fd):
        yield name, _read_report(directory_fd, name)


def save_report(directory, report) -> Path:
    """Save a complete report exclusively at mode 0600 in a private directory."""
    try:
        snapshot = deepcopy(report)
        _validate_report(snapshot)
        encoded = (json.dumps(snapshot, ensure_ascii=True, sort_keys=True,
                              indent=2, allow_nan=False) + "\n").encode("utf-8")
    except (TypeError, RecursionError) as exc:
        raise ValueError("Report cannot be serialized into history") from exc
    if len(encoded) > MAX_REPORT_BYTES:
        raise ValueError("Report exceeds the 8 MiB history limit")
    path, directory_fd = _open_directory(directory, create=True)
    name = None
    try:
        # Lock the directory inode, not a replaceable lockfile. Independent
        # opens in other processes/threads block until the complete write and
        # fsync finish; closing the descriptor releases the advisory lock.
        fcntl.flock(directory_fd, fcntl.LOCK_EX)
        count = 0
        for _name, _report in _reports(directory_fd):
            count += 1
        if count >= MAX_CANDIDATES:
            raise ValueError(f"History already contains {MAX_CANDIDATES} reports; archive older reports explicitly")
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
        for _ in range(3):
            name = f"linscope-{stamp}-{uuid.uuid4().hex}.json"
            try:
                fd = os.open(name, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC,
                             0o600, dir_fd=directory_fd)
            except FileExistsError:
                continue
            try:
                with os.fdopen(fd, "wb") as stream:
                    os.fchmod(stream.fileno(), 0o600)
                    stream.write(encoded)
                    stream.flush()
                    os.fsync(stream.fileno())
                os.fsync(directory_fd)
            except BaseException:
                try:
                    os.unlink(name, dir_fd=directory_fd)
                except OSError:
                    pass
                raise
            return path / name
        raise FileExistsError("Unable to allocate a unique history filename")
    finally:
        os.close(directory_fd)


def list_history(directory, limit=20) -> list[dict]:
    """List newest saved reports, validating all bounded LinScope candidates."""
    if type(limit) is not int or not 1 <= limit <= MAX_CANDIDATES:
        raise ValueError(f"History limit must be an integer in 1..{MAX_CANDIDATES}")
    path, directory_fd = _open_directory(directory)
    if directory_fd is None:
        return []
    try:
        fcntl.flock(directory_fd, fcntl.LOCK_SH)
        result = []
        for name, report in _reports(directory_fd):
            if len(result) < limit:
                result.append({"path": str(path / name), "name": name,
                               "generated_at": report["generated_at"], "host": report["host"]["name"],
                               "profile": report["host"]["profile"], "version": report["tool"]["version"],
                               "findings_count": len(report["findings"])})
        return result
    finally:
        os.close(directory_fd)


def latest_compatible(directory, report) -> dict | None:
    """Read the latest compatible saved report, or None; never mutate inputs."""
    _validate_report(report)
    _, directory_fd = _open_directory(directory)
    if directory_fd is None:
        return None
    try:
        fcntl.flock(directory_fd, fcntl.LOCK_SH)
        result = None
        for _, saved in _reports(directory_fd):
            if any(saved["host"][key] != report["host"][key] for key in ("name", "system", "profile")):
                continue
            if saved.get("scope") != report.get("scope"):
                continue
            if "scope" not in saved and {f["category"] for f in saved["findings"]} != {f["category"] for f in report["findings"]}:
                continue
            if result is None:
                result = saved
        return result
    finally:
        os.close(directory_fd)
